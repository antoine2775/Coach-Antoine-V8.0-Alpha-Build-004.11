// Tableaux stables : la frappe ou un nouveau rendu ne redémarrent pas le lecteur.
const sequences = Object.fromEntries(Object.entries(dialogues).map(([ecran, ids]) => [ecran,
  Object.fromEntries(['tu', 'vous'].map(mode => [mode,
    Object.freeze(ids.map(id => `${import.meta.env.BASE_URL}${(VOIX_INSCRIPTION[id][mode] ?? VOIX_INSCRIPTION[id].commun)}`)),
  ])),
]));

export function sequenceInscription(ecran, mode) {
  return sequences[ecran]?.[mode === 'vous' ? 'vous' : 'tu'] ?? silence;
}
